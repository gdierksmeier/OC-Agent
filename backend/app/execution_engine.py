"""
Workflow execution engine (Phase 1 simulator).

Runs an agent's workflow task-by-task, records every step in the
execution_steps table, applies retries / fallbacks per task config,
and tallies tokens, cost and latency into the executions table.

The model_call and call_endpoint task types are stubbed so the platform
runs end-to-end without real LLM keys or live integrations. Replace
`_simulate_model_call` and `_simulate_endpoint_call` with real adapters
to go to production.
"""
from __future__ import annotations

import json
import random
import re
import time
import uuid
from datetime import datetime
from typing import Any

from sqlalchemy.orm import Session

from . import models


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

_VAR_PATTERN = re.compile(r"\{\{\s*([\w\.]+)\s*\}\}")


def _resolve_template(text: str, context: dict[str, Any]) -> str:
    """Replace {{ var.path }} placeholders using values from context."""
    if not text:
        return text

    def lookup(match: re.Match) -> str:
        path = match.group(1).split(".")
        value: Any = context
        for part in path:
            if isinstance(value, dict) and part in value:
                value = value[part]
            else:
                return match.group(0)  # leave unresolved
        return str(value)

    return _VAR_PATTERN.sub(lookup, text)


def _mask_sensitive(payload: dict, sensitive: list[str]) -> dict:
    """Return a shallow copy with sensitive keys masked for logs."""
    if not payload or not sensitive:
        return payload
    masked = dict(payload)
    for key in sensitive:
        if key in masked:
            masked[key] = "***MASKED***"
    return masked


